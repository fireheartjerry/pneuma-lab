"""Self-contained HTML "mind monitor" generated from a voice stream.

Pure and byte-deterministic: it injects a sorted-key JSON island into one inline
HTML/CSS/JS document (no external requests — safe to share and CSP-compatible).
The page renders the thought stream tick-by-tick from the embedded data; the
runtime reveal animation does not affect the generated bytes.
"""

from __future__ import annotations

import json
from pathlib import Path


def monitor_payload(stream: dict) -> dict:
    """Deterministic view model: per-tick rendered lines with credit + receipts."""
    by_tick: dict[int, list[dict]] = {}
    for atom, rendered in zip(stream["atoms"], stream["rendered"]):
        by_tick.setdefault(int(atom["tick"]), []).append(
            {
                "type": atom["type"],
                "credit_status": atom["credit_status"],
                "text": rendered.get("text_voiced") or rendered["text_deterministic"],
                "voice_status": rendered.get("voice_status", "deterministic_only"),
                "receipts": atom.get("receipts", []),
            }
        )
    ticks = [{"tick": t, "lines": by_tick[t]} for t in sorted(by_tick)]
    sidecar = stream.get("sidecar", {})
    return {
        "subject": stream["subject"],
        "mode": stream["mode"],
        "evidence_level": stream["evidence_level"],
        "run_id": stream["run_id"],
        "indicator_family_status": sidecar.get("indicator_family_status", {}),
        "ticks": ticks,
    }


