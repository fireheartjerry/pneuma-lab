"""Self-contained HTML "mind monitor" (v2) generated from a voice stream.

Pure and byte-deterministic in deterministic mode: it injects a sorted-key JSON
island (atoms + rendered + a per-tick internal-state panel) into one inline
HTML/CSS/JS document (no external requests — safe to share, CSP-compatible). The
page plays the thought stream tick-by-tick with a live internal-state panel and a
timeline scrubber. Runtime animation does not affect the generated bytes. When a
non-canonical voiced skin is attached, its text is shown but is NOT part of any
byte-determinism guarantee.
"""

