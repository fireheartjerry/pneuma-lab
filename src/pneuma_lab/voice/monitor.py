def render_html(stream: dict) -> str:
    """Render a self-contained, deterministic mind-monitor HTML document."""
    payload = monitor_payload(stream)
    data = json.dumps(payload, sort_keys=True, ensure_ascii=False)
    data = data.replace("</", "<\\/")
    subject = str(stream["subject"])
    return _TEMPLATE.replace("__DATA__", data).replace("__SUBJECT__", subject)


def write_monitor(stream: dict, out_path: str | Path) -> None:
    """Write the mind-monitor HTML to ``out_path`` (deterministic)."""
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_html(stream), encoding="utf-8", newline="\n")


