def _tick_panel(lines: list[dict], evidence_level: int) -> dict:
    pressure = None
    winner = None
    salience: dict = {}
    dominant_affect = None
    scar_strength = None
    predicted_error = None
    credit_counts: dict = {}
    for ln in lines:
        credit_counts[ln["credit_status"]] = (
            credit_counts.get(ln["credit_status"], 0) + 1
        )
        for r in ln.get("receipts", []):
            fp, val = r.get("field_path", ""), r.get("value")
            if (
                fp.startswith("control_pressure.")
                and not fp.endswith("authority_tier")
                and isinstance(val, (int, float))
            ):
                pressure = float(val)
            elif fp == "workspace_broadcast.winning_faculty":
                winner = val
            elif fp.startswith("salience_scores.") and isinstance(val, (int, float)):
                salience[fp.split(".", 1)[1]] = float(val)
            elif (
                fp.startswith("shift.")
                and not fp.endswith(".from")
                and isinstance(val, (int, float))
            ):
                dominant_affect = {"dim": fp.split(".", 1)[1], "value": float(val)}
            elif fp == "psyche_state.derived_signals.scar_strength" and isinstance(
                val, (int, float)
            ):
                scar_strength = float(val)
            elif fp == "psyche_state.self_model.predicted_error" and isinstance(
                val, (int, float)
            ):
                predicted_error = float(val)
    return {
        "pressure": pressure,
        "winner": winner,
        "salience": salience,
        "dominant_affect": dominant_affect,
        "scar_strength": scar_strength,
        "predicted_error": predicted_error,
        "credit_counts": credit_counts,
        "evidence_level": evidence_level,
    }


def monitor_payload(stream: dict) -> dict:
    """Deterministic view model: per-tick rendered lines + internal-state panel."""
    by_tick: dict[int, list[dict]] = {}
    for atom, rendered in zip(stream["atoms"], stream["rendered"]):
        by_tick.setdefault(int(atom["tick"]), []).append(
            {
                "type": atom["type"],
                "credit_status": atom["credit_status"],
                "text": rendered.get("text_voiced") or rendered["text_deterministic"],
                "voice_status": rendered.get("voice_status", "deterministic_only"),
                "receipts": atom.get("receipts", []),
            }
        )
    ev = stream["evidence_level"]
    ticks = [
        {"tick": t, "lines": by_tick[t], "panel": _tick_panel(by_tick[t], ev)}
        for t in sorted(by_tick)
    ]
    sidecar = stream.get("sidecar", {})
    return {
        "subject": stream["subject"],
        "mode": stream["mode"],
        "evidence_level": ev,
        "run_id": stream["run_id"],
        "indicator_family_status": sidecar.get("indicator_family_status", {}),
        "ticks": ticks,
    }


